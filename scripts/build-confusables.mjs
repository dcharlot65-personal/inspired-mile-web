// Builds src/lib/verse/confusables.ts: the letters that are drawn like a Latin letter, from
// Unicode's own data (UTS #39, Unicode Security Mechanisms, confusables.txt), so that the
// engine reads a word "as seen" from a published table, not from a list someone typed.
//
//   node scripts/build-confusables.mjs [path to a downloaded confusables.txt]
//
// With no path the file is downloaded from unicode.org (the pinned version below). Either way
// its sha256 must be the one recorded here: a different file is refused, not used.
//
// What is kept: each entry whose source is one letter that compatibility normalisation (NFKC)
// leaves alone (cleanVerse applies NFKC first, so full-width and mathematical letters are plain
// by then), and whose prototype, once its combining marks are taken off, is one Latin letter
// a-z or A-Z ("ø" is o with a long solidus overlay: o). Entries whose prototype is several
// letters ("m" looks like "rn") are left out: a letter is read as one letter or not at all.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const VERSION = '18.0.0';
const URL = `https://www.unicode.org/Public/${VERSION}/security/confusables.txt`;
const SHA256 = '6ed3ee967c9dfdf6677d563c9985182fbc50a2efb7d6059cd57b2e2ce18f5b92';
const OUT = 'src/lib/verse/confusables.ts';

const text = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(URL)).text();
const sha = createHash('sha256').update(text, 'utf8').digest('hex');
if (sha !== SHA256) {
  console.error(`confusables.txt has sha256 ${sha}, not the recorded ${SHA256}. Check the new file and update VERSION and SHA256.`);
  process.exit(1);
}
const dated = /^# Date: (.*)$/m.exec(text)?.[1] ?? '?';
const version = /^# Version: (.*)$/m.exec(text)?.[1] ?? '?';
if (version !== VERSION) throw new Error(`the file says version ${version}, expected ${VERSION}`);

const pairs = [];
for (const line of text.split('\n')) {
  const m = /^([0-9A-F]+) ;\t([0-9A-F ]+) ;\tMA/.exec(line);
  if (!m) continue;
  const src = String.fromCodePoint(parseInt(m[1], 16));
  if (!/^\p{L}$/u.test(src) || src.normalize('NFKC') !== src) continue;
  const target = m[2].trim().split(' ').map((h) => String.fromCodePoint(parseInt(h, 16))).join('').normalize('NFD').replace(/\p{M}/gu, '');
  if (!/^[A-Za-z]$/.test(target) || target === src) continue;
  pairs.push([src, target]);
}
pairs.sort((a, b) => a[0].codePointAt(0) - b[0].codePointAt(0));
const data = pairs.map(([s, t]) => s + t).join('');
// Every source is a BMP letter in this version; the reader splits by code point, so an astral one would also work.
const src = `/**
 * GENERATED by scripts/build-confusables.mjs. Do not edit: run the script again.
 *
 * Letters drawn like a Latin letter, from Unicode's confusables.txt (UTS #39), version
 * ${VERSION} (dated ${dated}), sha256 ${SHA256}. ${pairs.length} letters: each kept entry's
 * source is one letter that NFKC leaves alone, and its prototype is one Latin letter once
 * its combining marks are taken off. The data is Unicode's, under the Unicode License v3
 * (https://www.unicode.org/license.txt): Copyright 1991-2026 Unicode, Inc.
 *
 * Read by text.ts (lookAlike): a letter and its Latin prototype, one after the other.
 */
export const CONFUSABLES_VERSION = '${VERSION}';
export default ${JSON.stringify(data)};
`;
writeFileSync(OUT, src);
console.log(`${OUT}: ${pairs.length} letters, ${Buffer.byteLength(src)} bytes (Unicode ${version}, ${dated})`);
