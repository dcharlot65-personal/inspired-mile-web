// Builds the generated language files of the play content from their sources:
//
//   trivia/<lang>.txt        n | question | option 0 | option 1 | option 2 | option 3
//                            "=" for an option that is a name: it is filled from the names table
//   challenges/<lang>.tsv    see challenges/README.md
//   wikidata-labels.json     the names table's source (fetch-wikidata.py), picks.tsv its hand choices
//
//   -> src/i18n/pages/trivia/<lang>.ts, src/i18n/pages/challenges/<lang>.ts
//   -> docs/language/data/content-names.tsv (every name used, its Wikidata item and how it was arrived at)
//
// Run: node scripts/lang-content/build.mjs        (exits 1 and writes nothing for a language with errors)
//      node scripts/lang-content/build.mjs --check    writes nothing; exits 1 if a generated file is not what
//                                                     its sources make (play-areas.test.ts runs this)
import { existsSync, mkdirSync, readFileSync, writeFileSync as write } from 'node:fs';
import { join } from 'node:path';
import { HERE, ROOT, LANGS, entities, gameNames, nameOf, readTsv, ucfirst } from './lib.mjs';

const { TRIVIA_BANK } = await import(join(ROOT, 'src/lib/trivia.ts'));
const { CHALLENGE_BANK } = await import(join(ROOT, 'src/lib/challenges.ts'));
const optionKeys = JSON.parse(readFileSync(join(HERE, 'trivia-options.json'), 'utf8'));
const q = (s) => JSON.stringify(s);
let failed = false;
const CHECK = process.argv.includes('--check');
const stale = [];
function writeFileSync(file, text) {
  if (!CHECK) return write(file, text);
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) stale.push(file.slice(ROOT.length + 1));
}
const fail = (m) => { failed = true; console.error('ERROR ' + m); };

// ---------- trivia ----------
for (const lang of LANGS) {
  const file = join(HERE, 'trivia', `${lang}.txt`);
  if (!existsSync(file)) { console.log(`trivia ${lang}: no source yet`); continue; }
  const rows = new Map();
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const parts = line.split(' | ').map((p) => p.trim());
    if (parts.length !== 6) { fail(`trivia ${lang}: line has ${parts.length} fields, wants 6: ${line.slice(0, 60)}`); continue; }
    if (rows.has(Number(parts[0]))) fail(`trivia ${lang}: question ${parts[0]} twice`);
    rows.set(Number(parts[0]), parts.slice(1));
  }
  const out = [];
  TRIVIA_BANK.forEach((en, n) => {
    const row = rows.get(n);
    if (!row) return fail(`trivia ${lang}: question ${n} missing`);
    out.push(`  'trivia.${n}.q': ${q(row[0])},`);
    en.options.forEach((_, i) => {
      const ent = optionKeys[n][i];
      let text = row[1 + i];
      if (text === '=') {
        if (!ent) return fail(`trivia ${lang}: ${n} option ${i} is "=" but "${en.options[i]}" is not a name in trivia-options.json`);
        text = ucfirst(nameOf(ent.key, lang, ent.which).name);
      }
      if (!text) return fail(`trivia ${lang}: ${n} option ${i} empty`);
      out.push(`  'trivia.${n}.o${i}': ${q(text)},`);
    });
  });
  if (failed) continue;
  writeFileSync(join(ROOT, 'src/i18n/pages/trivia', `${lang}.ts`), `// GENERATED by scripts/lang-content/build.mjs from scripts/lang-content/trivia/${lang}.txt and the
// Wikidata names table. Do not edit: change the source and run the script.
const messages: Record<string, string> = {
${out.join('\n')}
};

export default messages;
`);
  console.log(`trivia ${lang}: ${rows.size} questions`);
}

// ---------- challenges ----------
// challenges/<lang>.tsv: n <TAB> the line in the published translation <TAB> missing words, | separated
//   <TAB> source id (a row of challenges/sources.tsv, which names translator, edition, URL and status)
const sources = new Map(readTsv(join(HERE, 'challenges', 'sources.tsv')).map((r) => [r[0], { id: r[0], lang: r[1], work: r[2], translator: r[3], died: r[4], url: r[5], status: r[6] }]));
const dropped = [];
for (const lang of LANGS) {
  const rows = readTsv(join(HERE, 'challenges', `${lang}.tsv`));
  const out = [];
  const ids = [];
  for (const [nRaw, full, missingRaw, sourceId] of rows) {
    const n = Number(nRaw);
    const en = CHALLENGE_BANK[n];
    const src = sources.get(sourceId);
    if (!en) { fail(`challenges ${lang}: no challenge ${nRaw}`); continue; }
    if (!src || src.lang !== lang) { fail(`challenges ${lang}: ${n} names source "${sourceId}", which sources.tsv does not have for ${lang}`); continue; }
    const missing = missingRaw.split('|');
    // Blank each missing word, in order, at its first occurrence after the previous one.
    let display = '', rest = full, ok = true;
    for (const w of missing) {
      const at = rest.toLocaleLowerCase(lang).indexOf(w.toLocaleLowerCase(lang));
      if (at < 0) { ok = false; fail(`challenges ${lang}: ${n} "${w}" is not in the line (after the previous blank): ${full}`); break; }
      display += rest.slice(0, at) + '___';
      rest = rest.slice(at + w.length);
    }
    if (!ok) continue;
    display += rest;
    const play = Object.entries(gameNames).find(([k, names]) => /^[pw]\./.test(k) && names.includes(en.play));
    const who = Object.entries(gameNames).find(([k, names]) => /^[ch]\./.test(k) && names.includes(en.character));
    const whoName = who ? nameOf(who[0], lang, who[1].indexOf(en.character)).name : en.character;
    ids.push(n);
    out.push(`  'challenge.${n}.full': ${q(full)},`, `  'challenge.${n}.display': ${q(display)},`, `  'challenge.${n}.missing': ${q(missing.join('|'))},`,
      `  'challenge.${n}.play': ${q(play ? nameOf(play[0], lang).name : en.play)},`, `  'challenge.${n}.character': ${q(whoName)},`, `  'challenge.${n}.translator': ${q(src.translator)},`);
  }
  CHALLENGE_BANK.forEach((c, n) => { if (!ids.includes(n)) dropped.push([lang, n, c.play, c.fullQuote]); });
  writeFileSync(join(ROOT, 'src/i18n/pages/challenges', `${lang}.ts`), `// GENERATED by scripts/lang-content/build.mjs from scripts/lang-content/challenges/${lang}.tsv.
// Do not edit: change the source and run the script. Each line is quoted from a published
// translation named in scripts/lang-content/challenges/sources.tsv; a challenge with no such
// line in this language is left out (docs/language/CONTENT-PROVENANCE.md).
const messages: Record<string, string> = {
  'challenges.ids': ${q(ids.join(','))},
${out.join('\n')}
};

export default messages;
`);
  console.log(`challenges ${lang}: ${ids.length} of ${CHALLENGE_BANK.length}`);
}

// ---------- the names table, for the provenance file ----------
if (!CHECK) mkdirSync(join(ROOT, 'docs/language/data'), { recursive: true });
const lines = ['key\twikidata\tenglish (game)\t' + LANGS.map((l) => `${l}\t${l}:how`).join('\t')];
for (const key of Object.keys(gameNames)) {
  gameNames[key].forEach((g, which) => {
    lines.push([key, entities[key].id, g, ...LANGS.flatMap((l) => { const r = nameOf(key, l, which); return [r.name, r.how + (r.check ? '?' : '')]; })].join('\t'));
  });
}
writeFileSync(join(ROOT, 'docs/language/data/content-names.tsv'), lines.join('\n') + '\n');
writeFileSync(join(ROOT, 'docs/language/data/challenges-dropped.tsv'), 'lang\tchallenge\twork\tEnglish line\n' + dropped.map((d) => d.join('\t')).join('\n') + '\n');
if (CHECK) {
  if (stale.length) console.error('NOT WHAT THE SOURCES MAKE (run node scripts/lang-content/build.mjs):\n  ' + stale.join('\n  '));
  else console.log('every generated file is what its sources make');
}
if (failed || stale.length) process.exit(1);
