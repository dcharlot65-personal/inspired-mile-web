// Builds src/lib/verse/function-words/<lang>.ts: the little words of each language other than
// English (English keeps text.ts STOP_WORDS), from the stopwords-iso collection (npm
// stopwords-iso 1.1.0, MIT licence, github.com/stopwords-iso). The copy measure and the
// substance a multiplier multiplies count only the words that carry meaning (text.ts
// isContentWord); these lists say which do not.
//
//   node scripts/build-function-words.mjs [path to stopwords-iso-1.1.0.tgz]
//
// Without a path the package is downloaded from the npm registry. Its sha256 must be the one
// recorded here. Entries with no letter (digits, punctuation) are left out, and so are entries
// of more than one word (Vietnamese "bao giờ"): the engine reads a verse word by word.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const URL = 'https://registry.npmjs.org/stopwords-iso/-/stopwords-iso-1.1.0.tgz';
const SHA256 = 'e09c4b231be8c26eba98cf22468d0c2bcc0fd564b57b5b6304537373c24d1130';
const LANGS = ['es', 'fr', 'de', 'it', 'pt', 'pl', 'ru', 'ar', 'hi', 'zh', 'ja', 'ko', 'vi', 'th', 'id'];
const OUT = 'src/lib/verse/function-words';

const dir = mkdtempSync(join(tmpdir(), 'stopwords-iso-'));
const tgz = process.argv[2] ?? join(dir, 'stopwords-iso-1.1.0.tgz');
if (!process.argv[2]) writeFileSync(tgz, Buffer.from(await (await fetch(URL)).arrayBuffer()));
const sha = createHash('sha256').update(readFileSync(tgz)).digest('hex');
if (sha !== SHA256) throw new Error(`${tgz} has sha256 ${sha}, not ${SHA256}`);
execFileSync('tar', ['xzf', tgz, '-C', dir]);
const all = JSON.parse(readFileSync(join(dir, 'package', 'stopwords-iso.json'), 'utf8'));

mkdirSync(OUT, { recursive: true });
for (const lang of LANGS) {
  const words = [...new Set((all[lang] ?? []).map((w) => w.normalize('NFC').toLowerCase().trim()).filter((w) => /\p{L}/u.test(w) && !/\s/.test(w)))].sort();
  const src = `/**
 * GENERATED by scripts/build-function-words.mjs. Do not edit: run the script again.
 *
 * The little words of this language (${words.length}), from stopwords-iso 1.1.0
 * (npm stopwords-iso, tarball sha256 ${SHA256}), by Gene Diaz and its
 * contributors, under the MIT licence its package.json declares. Loaded with the language's
 * pack (packs/index.ts loadPack).
 */
export default ${JSON.stringify(words)};
`;
  writeFileSync(join(OUT, `${lang}.ts`), src);
  console.log(lang, words.length, Buffer.byteLength(src));
}
