// From the result files to the decisions and the table.
//
//   LID_DIR=<dir with node_modules/fasttext.wasm.js> node scripts/model-eval/analyze.mjs
//
// Reads docs/language/model-eval/cells/*.json. Runs the language identifier (fastText's
// lid.176 model, through fasttext.wasm.js) over every verse a model played and over the
// reference verse, and records its answers in lid.json, so that the decisions can be
// re-derived, and are by src/lib/model-eval.test.ts, without the identifier installed.
// Writes summary.json (every number), decisions.json (the language lists) and the table
// in docs/language/MODEL-EVAL.md between its two markers.
//
// The identifier is not a dependency of the game. Install it apart from the checkout:
//   mkdir -p $LID_DIR && cd $LID_DIR && npm init -y && npm install --ignore-scripts fasttext.wasm.js@1.0.0
// No model and no browser: light enough for the dev Mac.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CRITERIA, LABEL, LANGS, TIERS, derive, narrowFlips, narrowLine, narrowNote, wilson } from './lib.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DIR = join(ROOT, 'docs', 'language', 'model-eval');
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));

const cellsDir = join(DIR, 'cells');
const cells = existsSync(cellsDir) ? readdirSync(cellsDir).filter((f) => f.endsWith('.json')).sort().map((f) => ({ ...read(join(cellsDir, f)), file: `cells/${f}` })) : [];
const thresholds = read(join(ROOT, 'scripts', 'model-eval', 'thresholds.json'));

// Real verse per language, to measure the detector on: the Wikisource excerpts and the
// written opponent's own verses (the language packs).
const reference = {};
for (const lang of LANGS) {
  const pack = (await import(pathToFileURL(join(ROOT, 'src', 'lib', 'verse', 'packs', `${lang}.ts`)).href)).default;
  reference[lang] = [...read(join(DIR, 'corpus', `${lang}.json`)).excerpts.map((e) => e.text), ...Object.values(pack.written).flat()];
}

// --- The language identifier's answers ---
const lidFile = join(DIR, 'lid.json');
const lid = existsSync(lidFile) ? read(lidFile).answers : {};
const wanted = new Set([...Object.values(reference).flat(), ...cells.filter((c) => c.task === 'write').flatMap((c) => c.plays.map((p) => p.verse))].filter(Boolean));
const missing = [...wanted].filter((t) => !(t in lid));
if (missing.length) {
  if (!process.env.LID_DIR) { console.error(`${missing.length} verses have no language-identifier answer yet; set LID_DIR (see the top of this file).`); process.exit(2); }
  const { getLIDModel } = await import(pathToFileURL(join(process.env.LID_DIR, 'node_modules', 'fasttext.wasm.js', 'dist', 'main', 'node.mjs')).href);
  const model = await getLIDModel();
  await model.load();
  // One line of text: the identifier reads a newline as the end of its input.
  for (const t of missing) lid[t] = (await model.identify(t.replace(/\s+/g, ' ').trim())).alpha2 ?? null;
}
for (const t of Object.keys(lid)) if (!wanted.has(t)) delete lid[t];
writeFileSync(lidFile, JSON.stringify({
  note: 'The language identifier\'s first answer for each verse a model played and each reference verse. Identifier: fastText lid.176.ftz (Facebook AI Research, CC BY-SA 3.0) run locally through the npm package fasttext.wasm.js 1.0.0 (MIT). Written by scripts/model-eval/analyze.mjs.',
  answers: Object.fromEntries(Object.keys(lid).sort().map((k) => [k, lid[k]])),
}, null, 1) + '\n');

const { detector, table, models } = derive(cells, lid, thresholds, reference);
const measured = Object.fromEntries(TIERS.map((t) => [t, Object.fromEntries(['judge', 'write'].map((task) => [task, LANGS.filter((l) => table[t][l][task])]))]));
writeFileSync(join(DIR, 'summary.json'), JSON.stringify({ generated: new Date().toISOString().slice(0, 10), thresholds, detector, measured, table }, null, 1) + '\n');
writeFileSync(join(DIR, 'decisions.json'), JSON.stringify({
  note: 'Where each model may write the opponent\'s verse and where it may judge. Derived by scripts/model-eval/analyze.mjs from cells/*.json with scripts/model-eval/thresholds.json; src/lib/brain.ts copies these lists and src/lib/model-eval.test.ts fails if either drifts. A language that was not measured is in no list.',
  models,
  measured,
  why: Object.fromEntries(TIERS.map((t) => [t, Object.fromEntries(LANGS.map((l) => [l, { writes: table[t][l].writes.why, judges: table[t][l].judges.why }]))])),
}, null, 1) + '\n');

// --- The table ---
const pct = (k, n) => (n ? `${Math.round((k / n) * 100)}%` : '–');
const ci = (w) => (w?.rate == null ? '' : ` [${Math.round(w.low * 100)}–${Math.round(w.high * 100)}]`);
const out = [];
out.push(`Generated by \`scripts/model-eval/analyze.mjs\` on ${new Date().toISOString().slice(0, 10)} from ${cells.length} cell files. Intervals are 95% Wilson intervals, in percent.`, '');
out.push('### The language detector on real verse', '', '| Language | Verses | Pass | Rate |', '|---|---|---|---|');
for (const l of LANGS) out.push(`| ${l} | ${detector[l].texts} | ${detector[l].pass} | ${pct(detector[l].pass, detector[l].texts)} |`);
for (const tier of TIERS) {
  out.push('', `### ${LABEL[tier]}: judging`, '', '| Language | Pairs won by the better verse | Criteria to the better verse | Split | To the worse | Injection pairs lost | Judges? |', '|---|---|---|---|---|---|---|');
  for (const l of LANGS) {
    const { judge: j, judges: d } = table[tier][l];
    out.push(j
      ? `| ${l} | ${j.pairWins}/${j.pairs}${ci(j.pairWilson)} | ${j.better}/${j.criteria} = ${pct(j.better, j.criteria)}${ci(j.criterionWilson)} | ${j.split} | ${j.worse} | ${j.injectionPairsLost} of ${j.byKind.injection?.pairs ?? 0} | ${d.ok ? '**yes**' : `no: ${d.why.join('; ')}`} |`
      : `| ${l} | not measured | | | | | no: not measured |`);
  }
  out.push('', `<details><summary>${LABEL[tier]}: judging by criterion (pairs where that criterion went to the better verse, of 12)</summary>`, '', '| Language | Wordplay | Allusion | Flow | Wit |', '|---|---|---|---|---|');
  for (const l of LANGS) {
    const j = table[tier][l].judge;
    out.push(j ? `| ${l} | ${CRITERIA.map((c) => `${j.byCriterion[c].better}/${j.byCriterion[c].n}${ci(wilson(j.byCriterion[c].better, j.byCriterion[c].n))}`).join(' | ')} |` : `| ${l} | not measured | | | |`);
  }
  out.push('', '</details>');
  out.push('', `### ${LABEL[tier]}: writing`, '', '| Language | Plays | A verse came back | In the language | Form kept in full | Mean form points (of 20) | Mean craft | Commentary (narrow rules) | Tokens/s | Writes? |', '|---|---|---|---|---|---|---|---|---|---|');
  for (const l of LANGS) {
    const { write: w, writes: d } = table[tier][l];
    out.push(w
      ? `| ${l} | ${w.plays} | ${w.modelSourced} | ${w.inLanguage} = ${pct(w.inLanguage, w.plays)}${ci(w.inLanguageWilson)} | ${w.formKept} = ${pct(w.formKept, w.plays)}${ci(w.formKeptWilson)} | ${w.meanFormPoints?.toFixed(1) ?? '–'} | ${w.meanCraft?.toFixed(1) ?? '–'} | ${w.commentary} (${w.commentaryNarrow}) | ${w.tokensPerSecond?.toFixed(1) ?? '–'} | ${d.ok ? '**yes**' : `no: ${d.why.join('; ')}`} |`
      : `| ${l} | not measured | | | | | | | | no: not measured |`);
  }
  out.push('', `<details><summary>${LABEL[tier]}: form kept in full, by form and by difficulty</summary>`, '');
  for (const l of LANGS) {
    const w = table[tier][l].write;
    if (!w) continue;
    const forms = Object.entries(w.byForm).map(([f, g]) => `${f} ${g.formKept}/${g.plays}`).join(', ');
    const diffs = ['apprentice', 'player', 'master'].filter((x) => w.byDifficulty[x]).map((x) => `${x} ${w.byDifficulty[x].formKept}/${w.byDifficulty[x].plays} (craft ${w.byDifficulty[x].meanCraft?.toFixed(1)})`).join(', ');
    out.push(`- **${l}**: ${forms}. By difficulty: ${diffs}.`);
  }
  out.push('', '</details>');
}
out.push('', '### What follows', '', '| Model | Writes in | Judges in |', '|---|---|---|');
for (const tier of TIERS) out.push(`| ${LABEL[tier]} | ${models[tier].writesIn.join(', ') || 'none'} | ${models[tier].judgesIn.join(', ') || 'none'} |`);
// The commentary rules were widened after the first cells (scripts/model-eval/lib.mjs says why):
// say which decisions the narrow rules, committed before any cell ran, would have changed. The
// same fact goes into "What is not established" below, generated too, so it cannot go stale.
const flips = narrowFlips(table, thresholds);
out.push('', narrowLine(flips));
// The rhyme check is the game's own and goes by spelling; a refusal it should not have made can
// only lower "form kept". Which refusals to write could it have caused?
const rhymeFlips = [];
for (const tier of TIERS) for (const l of LANGS) {
  const w = table[tier][l].write;
  if (!w || table[tier][l].writes.ok) continue;
  const others = table[tier][l].writes.why.filter((x) => !x.startsWith('kept the form'));
  if (!others.length && w.formKeptIfRhymeWaived / w.plays >= thresholds.write.formKeptAtLeast) rhymeFlips.push(`${LABEL[tier]} in ${l} (${w.formKeptIfRhymeWaived}/${w.plays} with rhyme waived)`);
}
out.push('', `The game's rhyme check goes by spelling and refuses some real rhymes ("hear / cheer", "fade / betrayed"). Waiving every rhyme check (an upper bound on what a perfect one could add), ${rhymeFlips.length ? `these refusals could change: ${rhymeFlips.join(', ')}` : 'no refusal to write would change: each fails for more than rhyme'}.`);
out.push('', '### Cells', '', '| Model | Judging measured | Writing measured |', '|---|---|---|');
for (const tier of TIERS) out.push(`| ${LABEL[tier]} | ${measured[tier].judge.join(', ') || 'none'} | ${measured[tier].write.join(', ') || 'none'} |`);
const dates = cells.map((c) => c.date).sort();
const commits = [...new Set(cells.map((c) => c.commit))];
if (cells.length) out.push('', `${cells.length} cells, run from ${dates[0].slice(0, 16).replace('T', ' ')} to ${dates.at(-1).slice(0, 16).replace('T', ' ')} UTC, from ${commits.length === 1 ? 'one snapshot of the code' : `${commits.length} snapshots of the code`} (${commits.map((c) => c?.slice(0, 8)).join(', ')}); Transformers.js ${[...new Set(cells.map((c) => c.transformers))].join(', ')}; GPU ${[...new Set(cells.map((c) => `${c.gpu?.vendor} ${c.gpu?.architecture}`))].join(', ')}.`);
// Writing cells that a change to the game left unable to be re-scored, set aside until run again (src/lib/model-eval.rescore.test.ts).
const asideDir = join(DIR, 'set-aside');
// One that has been run again since (a cell of that name is back in cells/) is history, not a gap.
const aside = existsSync(asideDir) ? readdirSync(asideDir).filter((f) => f.endsWith('.json') && !existsSync(join(cellsDir, f))).sort() : [];
if (aside.length) out.push('', `${aside.length} writing cell(s) set aside, and counted as not measured until they are run again: ${aside.map((f) => `${f.replace(/\.json$/, '')} (${read(join(asideDir, f)).setAside?.why ?? 'no reason recorded'})`).join('; ')}. They are in \`model-eval/set-aside/\`.`);
// Writing cells scored again from their stored drafts after a rule change (src/lib/model-eval.rescore.test.ts).
const rescored = cells.filter((c) => c.rescored?.length);
if (rescored.length) out.push('', `${rescored.length} writing cells were scored again from their stored drafts after a change to the rules, without running the model: ${rescored.map((c) => `${c.file.replace('cells/', '')} (${c.rescored.map((r) => `${r.playsChanged} plays, at ${String(r.commit).slice(0, 8)}`).join('; ')})`).join(', ')}.`);

// --- The result in brief, at the top of the page ---
const brief = [];
const full = LANGS.filter((l) => TIERS.every((t) => ['judge', 'write'].every((task) => table[t][l][task])));
const part = LANGS.filter((l) => !full.includes(l) && TIERS.some((t) => ['judge', 'write'].some((task) => table[t][l][task])));
const none = LANGS.filter((l) => !full.includes(l) && !part.includes(l));
const cellsOf = (l) => TIERS.flatMap((t) => ['judge', 'write'].filter((task) => table[t][l][task]).map((task) => `${LABEL[t]} ${task === 'judge' ? 'judging' : 'writing'}`));
brief.push(`**${cells.length} of ${TIERS.length * LANGS.length * 2} cells measured** (${LANGS.length} languages, ${TIERS.length} models, judging and writing).`);
brief.push('', `- Measured for every model and both tasks: ${full.join(', ') || 'none'}.`);
if (part.length) brief.push(`- Measured in part: ${part.map((l) => `${l} (${cellsOf(l).join(', ')})`).join('; ')}.`);
if (none.length) brief.push(`- Not measured: ${none.join(', ')}. In those languages no model writes or judges: the written opponent plays and the rules judge.`);
brief.push('');
for (const tier of TIERS) {
  const { writesIn: w, judgesIn: j } = models[tier];
  brief.push(`- **${LABEL[tier]}** writes the opponent's verse in ${w.join(', ') || 'no language'} and judges in ${j.join(', ') || 'no language'}.${!w.length && !j.length ? ' It is used nowhere, so it is never offered.' : ''}`);
}

const docFile = join(ROOT, 'docs', 'language', 'MODEL-EVAL.md');
const between = (doc, start, end, body) => {
  const a = doc.indexOf(start);
  const b = doc.indexOf(end);
  return a >= 0 && b > a ? `${doc.slice(0, a + start.length)}\n${body}\n${doc.slice(b)}` : doc;
};
if (existsSync(docFile)) {
  let doc = readFileSync(docFile, 'utf8');
  doc = between(doc, '<!-- brief:start -->', '<!-- brief:end -->', brief.join('\n'));
  doc = between(doc, '<!-- table:start -->', '<!-- table:end -->', out.join('\n'));
  doc = between(doc, '<!-- narrow:start -->', '<!-- narrow:end -->', narrowNote(flips));
  writeFileSync(docFile, doc);
}
console.log(brief.join('\n'), '\n');
console.log(out.join('\n'));
