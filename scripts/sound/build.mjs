/**
 * Keep sixty words with their dictionary counts as that language's syllable test set: the
 * dictionary's words of 2 to 14 characters in sorted order, taken at even steps, so the set
 * is the same on every build and nobody chose its words.
 */
function syllableSet(lang, source, unit, pairs) {
  const seen = new Set();
  // A count may be a list: the dictionary gives the word more than one pronunciation, and more than one count.
  const ok = (n) => (Array.isArray(n) ? n.length > 0 && n.every((x) => x > 0) : n > 0);
  const all = pairs.filter(([w, n]) => [...w].length >= 2 && [...w].length <= 14 && ok(n) && !seen.has(w) && seen.add(w)).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const words = [];
  for (let i = 0; i < 60 && all.length >= 60; i++) words.push(all[Math.floor(((i + 0.5) * all.length) / 60)]);
  syllSets[lang] = { source, unit, words };
}

const b36 = (n) => Math.min(35, n).toString(36);
const pct = (a, b) => (b ? Math.round((1000 * a) / b) / 10 : null);

function lines(file) {
  return readFileSync(join(SRC, file), 'utf8').split('\n').filter(Boolean);
}

/** Write a table: sorted, each word front-coded against the one before (see parseTable in sound/index.ts). */
function writeTable(lang, entries, note) {
  const words = [...entries.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  let prev = '';
  const out = [];
  for (const w of words) {
    let k = 0;
    while (k < prev.length && k < w.length && prev[k] === w[k] && k < 70) k++;
    // Never cut a surrogate pair in two.
    if (k > 0 && /[\ud800-\udbff]/.test(w[k - 1])) k--;
    out.push(String.fromCharCode(48 + k) + w.slice(k) + '\t' + entries.get(w));
    prev = w;
  }
  const text = out.join('\n');
  const body = `// Generated by scripts/sound/build.mjs. Do not edit: rebuild it.\n// ${note}\nexport default ${JSON.stringify(text)};\n`;
  writeFileSync(join(OUT, `${lang}.ts`), body);
  const size = { entries: words.length, bytes: Buffer.byteLength(body), gzipBytes: gzipSync(body, { level: 9 }).length };
  console.log(lang, JSON.stringify(size));
  return size;
}

// --- IPA ---

const IPA_VOWELS = 'aeiouyɑɐɒæɛɜəɘɪɨʉɯɤʊʌɔœøɵʏᵻ';
const isVowel = (ch) => IPA_VOWELS.includes(ch);
const GLIDES = 'jwɥ';

/** The first phonemic or phonetic transcription of an entry, brackets off; null if it has none usable. */
function cleanIpa(raw) {
  const s = raw.normalize('NFD').trim();
  if (!/^[\/\[].*[\/\]]$/.test(s) || s.includes(' ')) return null;
  return s.slice(1, -1).replace(/[()]/g, '').replace(/[\u0361\u035c‿]/g, '');
}

/** Syllable nuclei in an IPA string: vowels (a marked glide is none, a diphthong written with a tie-less glide mark is one) and syllabic consonants. */
function nuclei(ipa, diphthongs = []) {
  let s = ipa;
  // Each diphthong counts once; its stand-in begins no other diphthong ("aɪʊ" is aɪ + ʊ, not aɪ then aʊ).
  for (const d of diphthongs) s = s.split(d).join('ə');
  let n = 0;
  const cs = [...s];
  for (let i = 0; i < cs.length; i++) {
    if (cs[i] === '\u0329') n++;
    else if (isVowel(cs[i])) {
      let j = i + 1;
      let glide = false;
      while (j < cs.length && /[\u0300-\u036fːˑ]/.test(cs[j])) {
        if (cs[j] === '\u032f') glide = true;
        j++;
      }
      if (!glide) n++;
    }
  }
  return n;
}

/**
 * Syllables of a syllabified transcription: one more than its breaks. A break written twice
 * (".ˈ" in "/pri.ˈba.di/") is one break; until 2026-11-16 it counted as two, which put wrong
 * counts into the es, it and pt test sets ("automutilar", six).
 */
function syllablesOf(ipa, diphthongs) {
  if (!/[.]/.test(ipa)) return nuclei(ipa, diphthongs);
  return 1 + (ipa.replace(/^[ˈˌ.]+/, '').match(/[.ˈˌ]+/g) ?? []).length;
}

function kaikki(lang) {
  const out = [];
  for (const l of lines(`kaikki_${lang}.tsv`)) {
    const [word, ...ipas] = l.split('\t');
    const clean = ipas.map(cleanIpa).filter(Boolean);
    // An initialism is read letter by letter and shares its spelling with an ordinary word once
    // lower-cased (Indonesian "API", four syllables, against "api", fire): left out.
    const initialism = [...word].length > 1 && word === word.toUpperCase() && word !== word.toLowerCase();
    if (word && clean.length && !/[\s\d]/.test(word) && !initialism) out.push([word, clean]);
  }
  return out;
}

/** As kaikki(), with each entry's transcriptions as written (not yet cleaned or split). */
function kaikkiRaw(lang) {
  const out = [];
  for (const l of lines(`kaikki_${lang}.tsv`)) {
    const [word, ...ipas] = l.split('\t');
    const initialism = [...word].length > 1 && word === word.toUpperCase() && word !== word.toLowerCase();
    if (word && ipas.length && !/[\s\d]/.test(word) && !initialism) out.push([word, ipas]);
  }
  return out;
}

// --- Spanish, Italian, Portuguese: exceptions to the spelling rules ---

/** Letters from the stressed vowel to the end of `text`, by lining the spelling's vowel groups up with the transcription's. Null when they do not line up. */
function stressedTail(text, ipa, byQuality = false) {
  const groups = [];
  for (let i = 0; i < text.length; i++) {
    const v = 'aeiou'.includes(text[i]);
    const h = text[i] === 'h' && i > 0 && i + 1 < text.length && 'aeiou'.includes(text[i - 1]) && 'aeiou'.includes(text[i + 1]);
    if (v || h) {
      const g = groups[groups.length - 1];
      if (g && g.end === i) g.end = i + 1;
      else if (v) groups.push({ start: i, end: i + 1 });
    }
  }
  const runs = [];
  let cur = null;
  let stressNext = false;
  let stressed = null;
  const cs = [...ipa];
  const primary = ipa.lastIndexOf('ˈ');
  let pos = 0;
  for (const ch of cs) {
    const at = pos;
    pos += ch.length;
    if (ch === 'ˈ' && at === primary) {
      stressNext = true;
      continue;
    }
    if ('.ˈˌ'.includes(ch) || /[\u0300-\u036fːˑ]/.test(ch)) continue;
    if (isVowel(ch) || GLIDES.includes(ch)) {
      if (!cur) runs.push((cur = []));
      cur.push(ch);
      if (stressNext && isVowel(ch)) {
        stressed = { run: runs.length - 1, at: cur.length - 1 };
        stressNext = false;
      }
    } else cur = null;
  }
  if (!runs.length) return null;
  // A glide spelled with a consonant letter ("y", "ll", "j") is not part of a vowel group.
  const vocalic = runs.filter((r) => r.some(isVowel));
  if (primary < 0) {
    if (vocalic.length !== 1 || vocalic[0].filter(isVowel).length !== 1) return null;
    const r = runs.indexOf(vocalic[0]);
    stressed = { run: r, at: runs[r].findIndex(isVowel) };
  }
  if (!stressed) return null;
  const idx = vocalic.indexOf(runs[stressed.run]);
  if (idx < 0 || vocalic.length !== groups.length) return null;
  const g = groups[idx];
  const letters = [];
  for (let i = g.start; i < g.end; i++) if (text[i] !== 'h') letters.push(i);
  const run = runs[stressed.run];
  // Portuguese: the letter that spells the stressed vowel, where one in the group does. A group and
  // its sounds do not line up by position there: a closing l is said as a glide ("real", /ʁeˈaw/),
  // a nasal adds one ("alguém", /awˈɡẽj̃/), the u of "gu" is silent, and a variant may drop a vowel
  // ("caixa", /ˈka.ʃɐ/).
  if (byQuality) {
    const v = run[stressed.at].normalize('NFD')[0];
    const letter = /[aɐæ]/.test(v) ? 'a' : /[eɛ]/.test(v) ? 'e' : /[iɪ]/.test(v) ? 'i' : /[oɔ]/.test(v) ? 'o' : /[uʊ]/.test(v) ? 'u' : '';
    const match = letters.filter((i) => text[i] === letter);
    if (match.length === 1) return text.length - match[0];
  }
  const fromRight = run.length - stressed.at;
  const li = Math.max(0, letters.length - fromRight);
  return text.length - letters[li];
}

function romance(lang) {
  const entries = new Map();
  const m = { words: 0, countAgree: 0, stressChecked: 0, stressAgree: 0, unaligned: 0 };
  const seen = new Set();
  const cands = [];
  for (const [word, ipas] of kaikki(lang)) {
    const w = word.toLowerCase().normalize('NFC');
    if (seen.has(w) || !/^\p{L}+$/u.test(w)) continue;
    const text = romanceText(w);
    const rule = text === null ? null : syllablesByRule(w, lang);
    if (text === null || rule === null) continue;
    seen.add(w);
    const ipa = ipas.find((x) => /[.ˈ]/.test(x) || nuclei(x) === 1) ?? ipas[0];
    const n = syllablesOf(ipa);
    m.words++;
    if (n === rule) m.countAgree++;
    let t = stressedTail(text, ipa);
    if (lang === 'pt') {
      // The stress most of the word's transcriptions give: one odd variant ("seguinte", /si.ɡĩˈt͡ʃi/,
      // against three with /ˈɡĩ/) does not decide it.
      const votes = new Map();
      for (const x of ipas) {
        if (!(/[.ˈ]/.test(x) || nuclei(x) === 1)) continue;
        const v = stressedTail(text, x, true);
        if (v !== null) votes.set(v, (votes.get(v) ?? 0) + 1);
      }
      t = votes.size ? [...votes].reduce((a, b) => (b[1] > a[1] ? b : a))[0] : null;
    }
    if (t !== null) cands.push([w, n]);
    const starts = romanceStressByRule(w, lang) ?? [];
    let tailCode = '0';
    if (t === null) m.unaligned++;
    else {
      m.stressChecked++;
      const agree = starts.length > 0 && text.length - starts[0] === t;
      if (agree) m.stressAgree++;
      if (!agree || starts.length !== 1) tailCode = b36(t);
    }
    // The count is measured but never taken from the dictionary. Where the two differ the
    // dictionary splits two vowels the rule joins ("mio", "tuo", "via"), and verse joins them
    // too (synaeresis); overriding the rule made written hendecasyllables count twelve.
    const countCode = '0';
    if (countCode !== '0' || tailCode !== '0') entries.set(w, countCode + tailCode);
  }
  const size = writeTable(lang, entries, `${lang}: words whose syllable count or stress the spelling rule gets wrong. Source: Wiktionary (CC BY-SA 4.0) via kaikki.org.`);
  syllableSet(lang, 'Wiktionary (syllabified IPA) via kaikki.org', 'syllables', cands);
  measures[lang] = { ...measures[lang], source: 'Wiktionary via kaikki.org', dictionaryWords: m.words, ruleSyllablesAgree: pct(m.countAgree, m.words), ruleStressAgree: pct(m.stressAgree, m.stressChecked), stressChecked: m.stressChecked, notAligned: m.unaligned, table: size };
}

// --- Indonesian, Hindi: exceptions to the syllable rule ---

/**
 * What a word's transcriptions say about its syllables, against the spelling rule. A dictionary
 * often lists several (a careful and a casual one, a regional one), sorted in no useful order, so
 * no one of them stands for the word. The rule is overridden only where none agrees with it, and
 * then by the count most of them give. Returns the override (or null) and the counts listed, the
 * commonest first, for the test set.
 */
function resolveCounts(counts, rule) {
  const tally = new Map();
  for (const n of counts) tally.set(n, (tally.get(n) ?? 0) + 1);
  const listed = [...tally].sort((a, b) => b[1] - a[1]).map(([n]) => n);
  return { override: counts.length && !tally.has(rule) ? listed[0] : null, listed };
}

function countExceptions(lang, script, ruleFn) {
  const cands = [];
  const entries = new Map();
  let words = 0;
  let agree = 0;
  const all = new Map();
  for (const [word, ipas] of kaikki(lang)) {
    const w = word.toLowerCase().normalize('NFC');
    if (!script.test(w) || ruleFn(w) === null) continue;
    const list = all.get(w) ?? [];
    // Vowels, not syllable breaks: a transcription may mark only some of its breaks ("/apa.kah/")
    // or mark one twice ("/pri.ˈba.di/").
    for (const x of ipas) list.push(nuclei(x.replace(/ᵊ/g, '')));
    all.set(w, list);
  }
  for (const [w, counts] of all) {
    const rule = ruleFn(w);
    const { override, listed } = resolveCounts(counts.filter((n) => n > 0), rule);
    if (!listed.length) continue;
    cands.push([w, listed.length === 1 ? listed[0] : listed]);
    words++;
    if (override === null) agree++;
    else if (override < 36) entries.set(w, b36(override));
  }
  const size = writeTable(lang, entries, `${lang}: words whose syllable count the spelling rule gets wrong. Source: Wiktionary (CC BY-SA 4.0) via kaikki.org.`);
  syllableSet(lang, 'Wiktionary (IPA) via kaikki.org; every count its transcriptions give', 'syllables', cands);
  measures[lang] = { ...measures[lang], source: 'Wiktionary via kaikki.org', dictionaryWords: words, ruleSyllablesAgree: pct(agree, words), table: size };
}

// --- Russian: where the stress falls ---

function russian() {
  const RU_IPA_VOWELS = 'aæeɛiɨoɵuʉɐəɪʊᵻ';
  const stress = new Map();
  const cands = [];
  let words = 0;
  let skipped = 0;
  const add = (w, k) => {
    const s = stress.get(w) ?? '';
    if (!s.includes(k)) stress.set(w, s + k);
  };
  for (const [word, ipas] of kaikki('ru')) {
    const w = word.toLowerCase().normalize('NFC');
    if (!/^[а-яё]+$/.test(w) || w.length > 22) continue;
    const vowels = w.match(/[аеёиоуыэюя]/g) ?? [];
    if (vowels.length < 2) continue;
    words++;
    let any = false;
    for (const ipa of ipas) {
      const at = ipa.lastIndexOf('ˈ');
      if (at < 0) continue;
      const count = (s) => [...s].filter((c) => RU_IPA_VOWELS.includes(c)).length;
      if (count(ipa) !== vowels.length) continue;
      cands.push([w, count(ipa)]);
      const k = count(ipa.slice(at));
      if (k < 1 || k > 9) continue;
      any = true;
      if (w.includes('ё')) add(w.replace(/ё/g, 'е'), String(k));
      else add(w, String(k));
    }
    if (!any) skipped++;
  }
  const size = writeTable('ru', stress, 'ru: the stressed vowel of each word, counted from the end. Source: Wiktionary (CC BY-SA 4.0) via kaikki.org.');
  syllableSet('ru', 'Wiktionary (IPA: one vowel sound a syllable) via kaikki.org', 'syllables', cands);
  measures.ru = { ...measures.ru, source: 'Wiktionary via kaikki.org', dictionaryWords: words, notAligned: skipped, table: size };
}

// --- French: how each word is said ---

/**
 * French vowel groups in the spelling, the bounds a verse count must lie in. The fewest: every
 * run of vowel letters is one sound, and a closing mute e is not counted; a written "e" between
 * consonants is a syllable in verse even where speech drops it ("pe-tite", "se-maine"). The
 * most: an i, u or ou before another vowel may be sounded apart ("li-on", "nu-age", "jou-er"),
 * as may a vowel with a diaeresis ("na-ïf") and each side of a y between vowels ("pa-yer");
 * the u of "qu" and "gu" is only a spelling.
 */
/** Does the spelling close on a mute e: "e", "es" or "ent" after a consonant ("porte", "chaque", "parlent"; not "été", "vie")? */
function frenchMuteSpelling(w) {
  const sp = w.replace(/qu/g, 'k').replace(/gu(?=[eéèêëiïy])/g, 'g');
  return /[^aeiouyàâäéèêëîïôöùûü](e|es|ent)$/.test(sp) && /[aeiouyàâäéèêëîïôöùûü]/.test(sp.replace(/(e|es|ent)$/, ''));
}

function frenchSpelled(w, mute) {
  const V = 'aeiouy';
  const cs = [...w.normalize('NFD').replace(/œ/g, 'oe').replace(/æ/g, 'ae')];
  const ls = [];
  for (const c of cs) {
    if (/[\u0300-\u036f]/.test(c)) {
      if (ls.length && c === '\u0308') ls[ls.length - 1].apart = true;
      continue;
    }
    ls.push({ c, apart: false });
  }
  let fewest = 0;
  let most = 0;
  let prevVowel = false;
  for (let i = 0; i < ls.length; i++) {
    const { c, apart } = ls[i];
    const silentU = c === 'u' && i > 0 && (ls[i - 1].c === 'q' || (ls[i - 1].c === 'g' && 'eiy'.includes(ls[i + 1]?.c ?? '')));
    const vowel = V.includes(c) && !silentU;
    if (!vowel) {
      prevVowel = false;
      continue;
    }
    if (!prevVowel) {
      fewest++;
      most++;
    } else {
      const before = ls[i - 1].c;
      const ou = before === 'u' && ls[i - 2]?.c === 'o';
      if (apart || ((before === 'i' || before === 'u' || ou) && c !== 'i' && c !== 'u') || before === 'y') most++;
    }
    prevVowel = true;
  }
  if (mute) {
    fewest--;
    most--;
  }
  return { fewest: Math.max(1, fewest), most: Math.max(1, most) };
}

function french() {
  const FR_VOWEL = /^[aeiouyøœəɛɔɑ]/;
  // Transcriptions of Quebec French (affricates, lax high vowels, diphthongs before a consonant):
  // used for a word only when it has no other.
  const REGIONAL = /t\u0361s|d\u0361z|ɪ|ʏ|ʊ|ã|\u032f/;
  const variants = new Map();
  for (const l of lines('fra_latn_broad.tsv')) {
    const [word, pron] = l.split('\t');
    const w = word.toLowerCase().normalize('NFC');
    if (word.length > 1 && word === word.toUpperCase() && word !== w) continue;
    if (!pron || !/^[a-zàâäçéèêëîïôöùûüÿœæ'\-]+$/.test(w) || w.length > 24) continue;
    const phones = pron.normalize('NFC').split(' ').filter((p) => p !== '‿');
    // A closing schwa is the mute e said aloud: verse decides when it is a syllable (see "mute").
    while (phones.length > 1 && phones[phones.length - 1] === 'ə' && phones.slice(0, -1).some((p) => FR_VOWEL.test(p))) phones.pop();
    const n = phones.filter((p) => FR_VOWEL.test(p)).length;
    if (n < 1 || n > 35) continue;
    const list = variants.get(w) ?? [];
    list.push({ phones, n, regional: REGIONAL.test(pron.normalize('NFD')) });
    variants.set(w, list);
  }
  const by = new Map();
  for (const [w, all] of variants) {
    const standard = all.filter((v) => !v.regional);
    let use = standard.length ? standard : all;
    let muteSpelled = frenchMuteSpelling(w);
    // A closing "-ent" is said in a noun or adjective ("président", "content") and silent in a verb
    // ("ils président", "parlent"). Where the dictionary has both readings, verse is counted with
    // the one that says it, which is the commoner in verse; the rhyme keys keep both.
    const said = /ent$/.test(w) ? use.filter((v) => FR_VOWEL.test(v.phones[v.phones.length - 1])) : [];
    if (said.length) muteSpelled = false;
    const spelled = frenchSpelled(w, muteSpelled);
    const count = said.length ? said : use;
    // The fullest reading the spelling can hold ("p ə t i t", not "p t i t"; "ɛ d", not "a ɛ d"),
    // and never fewer syllables than verse gives the written vowels.
    const fits = count.filter((v) => v.n <= spelled.most);
    const best = fits.length ? fits.reduce((a, b) => (b.n > a.n ? b : a)) : count.reduce((a, b) => (b.n < a.n ? b : a));
    const n = Math.max(best.n, spelled.fewest);
    const lastIsVowel = FR_VOWEL.test(best.phones[best.phones.length - 1]);
    const mute = muteSpelled && !lastIsVowel;
    const keys = [];
    for (const v of [best, ...use]) {
      let i = v.phones.length - 1;
      while (i >= 0 && !FR_VOWEL.test(v.phones[i])) i--;
      const key = v.phones.slice(i).join('').replace(/ʀ|r/g, 'ʁ');
      if (!keys.includes(key) && keys.length < 3) keys.push(key);
    }
    by.set(w, { n, mute, keys });
  }
  const entries = new Map();
  for (const [w, e] of by) entries.set(w, b36(e.n) + (e.mute ? '+' : '') + e.keys.join('|'));
  const size = writeTable('fr', entries, 'fr: syllables as spoken, "+" for a closing mute e, and the rhyme (last vowel on). Source: Wiktionary (CC BY-SA 4.0) via WikiPron.');
  syllableSet('fr', 'Wiktionary (IPA) via WikiPron; a word alone, so a closing mute e is silent', 'syllables', [...by].map(([w, e]) => [w, e.n]));
  measures.fr = { ...measures.fr, source: 'Wiktionary via WikiPron', dictionaryWords: by.size, table: size };
}

// --- German: how each word is said ---

/**
 * German transcriptions as Wiktionary writes them, made comparable. A sound may carry the phonemic
 * and the phonetic form in one string ("/ˈlɔɪ.tə/ [ˈlɔe̠.t(ʰ)ə]"): the phonemic one is taken, so that
 * a regional phonetic variant does not stand for the word. Narrow transcriptions write diphthongs
 * without the mark of a glide ("hɛˈʁaus") and the vocalised r as a plain ɐ after a vowel ("baːɐ",
 * "fɛɐˈʁʏkt"): one syllable each. After a diphthong ɐ is a syllable ("ˈfɔʏ̯ɐ", Feu-er).
 */
function germanIpas(raws) {
  const parts = raws.flatMap((r) => r.trim().split(/\s+/));
  const clean = (xs) => xs.map(cleanIpa).filter(Boolean);
  return [...new Set([...clean(parts.filter((x) => x.startsWith('/'))), ...clean(parts)])];
}

function german() {
  // Diphthongs, with and without the tie or the glide mark. Never across a syllable break ("Pha.ra.o").
  const DIPH = ['aɪ', 'aʊ', 'ɔʏ', 'ɔɪ', 'ai', 'au', 'ae', 'aɛ', 'ao', 'ɔe', 'ɔø', 'ɔy', 'oɪ', 'ɛɪ'];
  const V = 'aeiouyɛɔœøɪʊʏɑæə';
  const by = new Map();
  let words = 0;
  for (const [word, raws] of kaikkiRaw('de')) {
    const w = word.toLowerCase().normalize('NFC');
    if (!/^[a-zäöüß]+$/.test(w) || w.length > 28) continue;
    for (const raw of germanIpas(raws).slice(0, 2)) {
      let ipa = raw.normalize('NFC').replace(/ʔ/g, '');
      ipa = ipa
        .normalize('NFD')
        .replace(/n̩|ŋ̩|m̩/g, (x) => 'ə' + x[0].replace('ŋ', 'n'))
        .replace(/l̩/g, 'əl')
        .replace(/əʁ|ər/g, 'ɐ')
        .replace(/ɐ̯|[ʀr]/g, 'ʁ')
        // χ is the "ch" of "Bach", not an r.
        .replace(/χ/g, 'x')
        .replace(/̯/g, '')
        .normalize('NFC');
      // ɐ after a vowel that is not the end of a diphthong is that vowel's r ("baːɐ" is "baːʁ").
      // (Each diphthong stands as one private-use character while this is decided.)
      // Not where that leaves fewer syllables than the spelling has: "eher" is ˈeː.ɐ, e-her.
      let r = ipa;
      DIPH.forEach((d, i) => (r = r.split(d).join(String.fromCharCode(0xe000 + i))));
      r = r.replace(new RegExp(`([${V}]ː?)ɐ`, 'g'), '$1ʁ');
      DIPH.forEach((d, i) => (r = r.split(String.fromCharCode(0xe000 + i)).join(d)));
      if (nuclei(r, DIPH) >= Math.min(nuclei(ipa, DIPH), syllablesByRule(w, 'de'))) ipa = r;
      // A closing n, l or m after a consonant that the spelling writes with an e is a syllable even
      // where the transcription does not mark it ("ˈvɔχn" for "Wochen", "vɛːɐ̯n" for "wären").
      const spelled = syllablesByRule(w, 'de');
      if (nuclei(ipa, DIPH) < spelled && /e(n|l|m|ln|rn|ns|ls)$/.test(w)) ipa = ipa.replace(new RegExp(`([^${V}ːˈˌ.])([nlmŋ])$`), '$1ə$2');
      const n = nuclei(ipa, DIPH);
      ipa = ipa.replace(/\./g, '');
      if (n < 1 || n > 35) continue;
      const at = Math.max(ipa.lastIndexOf('ˈ'), ipa.lastIndexOf('ˌ'));
      let tail = ipa.slice(at + 1).replace(/[ˈˌ]/g, '');
      if (at < 0 && n > 1) {
        // No stress written: take the last vowel that is not a reduced one.
        const cs = [...tail];
        let i = cs.length - 1;
        while (i >= 0 && !(isVowel(cs[i]) && !'əɐ'.includes(cs[i]))) i--;
        while (i > 0 && isVowel(cs[i - 1])) i--;
        tail = i < 0 ? tail : cs.slice(i).join('');
      }
      const cs = [...tail];
      const first = cs.findIndex(isVowel);
      if (first < 0) continue;
      const key = cs.slice(first).join('');
    const e = by.get(w) ?? { n, keys: [] };
      if (!e.keys.includes(key) && e.keys.length < 3) e.keys.push(key);
      by.set(w, e);
    }
    words++;
  }
  const entries = new Map();
  for (const [w, e] of by) entries.set(w, b36(e.n) + e.keys.join('|'));
  let agree = 0;
  for (const [w, e] of by) if (syllablesByRule(w, 'de') === e.n) agree++;
  const size = writeTable('de', entries, 'de: syllables, and the rhyme (last stressed vowel on). Source: Wiktionary (CC BY-SA 4.0) via kaikki.org.');
  syllableSet('de', 'Wiktionary (IPA) via kaikki.org', 'syllables', [...by].map(([w, e]) => [w, e.n]));
  measures.de = { ...measures.de, source: 'Wiktionary via kaikki.org', dictionaryWords: by.size, ruleSyllablesAgree: pct(agree, by.size), table: size };
}

// --- Thai: syllables and the last rime of each word ---

function thai() {
  const TONE = /^[˥˦˧˨˩]+$/;
  const by = new Map();
  for (const l of lines('tha_thai_broad.tsv')) {
    const [word, pron] = l.split('\t');
    const w = word.normalize('NFC');
    if (!pron || !/^[\u0e01-\u0e4e]+$/.test(w)) continue;
    const phones = pron.normalize('NFC').split(' ');
    const syls = [];
    let cur = [];
    for (const p of phones) {
      if (TONE.test(p)) {
        syls.push(cur);
        cur = [];
      } else cur.push(p);
    }
    if (!syls.length || cur.length) continue;
    const last = syls[syls.length - 1];
    const i = last.findIndex((p) => isVowel(p[0]));
    if (i < 0) continue;
    let key = last.slice(i).join('').normalize('NFD').replace(/ː?a\u032f/, 'a').replace(/\u031a/g, '').replace(/ʔ$/, '').normalize('NFC');
    // A word with several readings is taken in its shortest: "พล" is phon before it is pha-la.
    const e = by.get(w);
    if (!e || syls.length < e.n) by.set(w, { n: syls.length, keys: [key] });
    else if (syls.length === e.n && !e.keys.includes(key) && e.keys.length < 2) e.keys.push(key);
  }
  const entries = new Map();
  let ruleAll = 0;
  let mono = 0;
  let ruleMono = 0;
  for (const [w, e] of by) {
    entries.set(w, b36(e.n) + e.keys.join('|'));
    const r = thaiRimeBySpelling(w);
    const strip = (k) => k.replace(/ː/g, '');
    const ok = r !== null && e.keys.some((k) => strip(k) === strip(r));
    if (ok) ruleAll++;
    if (e.n === 1) {
      mono++;
      if (ok) ruleMono++;
    }
  }
  const size = writeTable('th', entries, 'th: syllables, and the rime of the last syllable. Source: Wiktionary (CC BY-SA 4.0) via WikiPron.');
  syllableSet('th', 'Wiktionary (IPA: one tone a syllable) via WikiPron', 'syllables', [...by].map(([w, e]) => [w, e.n]));
  measures.th = { ...measures.th, source: 'Wiktionary via WikiPron', dictionaryWords: by.size, spellingRuleRimeAgree: pct(ruleAll, by.size), oneSyllableWords: mono, spellingRuleRimeAgreeOneSyllable: pct(ruleMono, mono), table: size };
}

// --- Chinese: the rhyme group and tone of each character, and of the last character of words that settle it ---

// The sixteen groups of 中华通韵 as the Ministry of Education's 2018 call for poems printed them
// (docs/language/PHONETICS.md, "Chinese"), lettered a to p in that order, except that the third
// group, 鹅 (e ie üe), is split in two: q is e alone. The thirteen-rut scheme (十三辙) rhymes e
// with o and uo (梭波) and keeps ie and üe apart (乜斜), so e has to be able to answer both sides
// while o never answers ie. rhyme.ts (ZH_ALLIED) joins q to b and to c.
const ZH_GROUPS = { a: 'a ia ua', b: 'o uo', c: 'ie üe ê', q: 'e', d: 'i -i', e: 'u', f: 'ü', g: 'ai uai', h: 'ei ui', i: 'ao iao', j: 'ou iu', k: 'an ian uan üan', l: 'en in un ün', m: 'ang iang uang', n: 'eng ing ueng', o: 'ong iong', p: 'er' };
const ZH_FINAL = new Map();
for (const [g, fs] of Object.entries(ZH_GROUPS)) for (const f of fs.split(' ')) ZH_FINAL.set(f, g);
const TONE_MARKS = { '\u0304': 1, '\u0301': 2, '\u030c': 3, '\u0300': 4 };

/** A pinyin syllable ("xíng", "lü4", "lu:4") as rhyme group and tone, or null if it is not one ("m", "r"). */
function pinyinCode(raw) {
  let s = raw.toLowerCase().replace(/u:/g, 'ü').replace(/v/g, 'ü');
  let tone = 5;
  const digit = /([1-5])$/.exec(s);
  if (digit) {
    tone = Number(digit[1]);
    s = s.slice(0, -1);
  }
  let out = '';
  for (const ch of s.normalize('NFD')) {
    if (TONE_MARKS[ch]) tone = TONE_MARKS[ch];
    else out += ch;
  }
  s = out.normalize('NFC');
  if (s === 'er' || s === 'r') return s === 'er' ? `p${tone}` : null;
  const m = /^(zh|ch|sh|[bpmfdtnlgkhjqxrzcsyw])?(.*)$/.exec(s);
  const init = m[1] ?? '';
  let fin = m[2];
  if (!fin) return null;
  if (init === 'y') fin = fin === 'u' ? 'ü' : fin.startsWith('u') ? 'ü' + fin.slice(1) : fin.startsWith('i') ? fin : fin === 'ou' ? 'iu' : 'i' + fin;
  else if (init === 'w') fin = fin === 'u' ? 'u' : fin === 'ei' ? 'ui' : fin === 'en' ? 'un' : fin === 'o' ? 'uo' : 'u' + fin;
  else if ('jqx'.includes(init) && init && fin.startsWith('u')) fin = 'ü' + fin.slice(1);
  else if (['zh', 'ch', 'sh', 'r', 'z', 'c', 's'].includes(init) && fin === 'i') fin = '-i';
  if (fin === 'iou') fin = 'iu';
  if (fin === 'uei') fin = 'ui';
  if (fin === 'uen') fin = 'un';
  if (fin === 'ue') fin = 'üe';
  if (fin === 'io' || fin === 'lo') fin = 'o';
  const g = ZH_FINAL.get(fin);
  return g ? `${g}${tone}` : null;
}

function chinese() {
  const fields = new Map();
  for (const l of lines('unihan/Unihan_Readings.txt')) {
    if (l[0] === '#') continue;
    const [cp, field, value] = l.split('\t');
    if (!['kMandarin', 'kTGHZ2013', 'kXHC1983', 'kHanyuPinlu'].includes(field)) continue;
    const ch = String.fromCodePoint(parseInt(cp.slice(2), 16));
    const f = fields.get(ch) ?? {};
    f[field] = value.split(' ').map((x) => x.replace(/^.*:/, '').replace(/\(\d+\)$/, ''));
    fields.set(ch, f);
  }
  const entries = new Map();
  const groupsOf = new Map();
  let several = 0;
  for (const [ch, f] of fields) {
    // The customary reading first. Then, for a common character, the readings counted in running
    // speech (kHanyuPinlu); for any other, those of the standard dictionaries. A common character's
    // rare dictionary readings are left out: 無 is wú, and its mó of 南無 let "雪 / 無" through.
    const readings = [...(f.kMandarin ?? []), ...(f.kHanyuPinlu ?? f.kTGHZ2013 ?? f.kXHC1983 ?? [])];
    const codes = [...new Set(readings.map(pinyinCode).filter(Boolean))];
    if (!codes.length) continue;
    entries.set(ch, codes.join(''));
    const gs = new Set(codes.map((c) => c[0]));
    groupsOf.set(ch, gs);
    if (gs.size > 1) several++;
  }
  const chars = entries.size;
  let words = 0;
  const wordCodes = new Map();
  for (const l of lines('cedict.txt')) {
    if (l[0] === '#') continue;
    const m = /^(\S+) (\S+) \[([^\]]+)\]/.exec(l);
    if (!m) continue;
    const syl = m[3].split(' ');
    const code = pinyinCode(syl[syl.length - 1]);
    if (!code) continue;
    for (const w of new Set([m[1], m[2]])) {
      const cs = [...w];
      if (cs.length < 2 || cs.length > 4 || cs.length !== syl.length || !cs.every((c) => /\p{Script=Han}/u.test(c))) continue;
      const gs = groupsOf.get(cs[cs.length - 1]);
      if (!gs || gs.size < 2) continue;
      const have = wordCodes.get(w) ?? '';
      if (!have.includes(code)) wordCodes.set(w, have + code);
    }
  }
  for (const [w, c] of wordCodes) {
    entries.set(w, c);
    words++;
  }
  const size = writeTable('zh', entries, 'zh: rhyme group (a-q, 中华通韵 with e apart) and tone of each reading of a character; for a word, of its last character. Sources: Unicode Unihan 18.0 (Unicode licence), CC-CEDICT (CC BY-SA 4.0).');
  const zhc = [];
  for (const l of lines('cedict.txt')) {
    const m = /^(\S+) (\S+) \[([^\]]+)\]/.exec(l);
    if (m && !/\br5\b|xx5/.test(m[3]) && [...m[2]].every((c) => /\p{Script=Han}/u.test(c))) zhc.push([m[2], m[3].split(' ').length]);
  }
  syllableSet('zh', 'CC-CEDICT (pinyin syllables)', 'syllables', zhc);
  measures.zh = { ...measures.zh, source: 'Unihan kMandarin/kHanyuPinlu/kTGHZ2013/kXHC1983; CC-CEDICT', characters: chars, charactersWithSeveralRhymeGroups: several, wordsThatSettleAReading: words, table: size };
}

