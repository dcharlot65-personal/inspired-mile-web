// Builds the per-language sound tables in src/lib/verse/sound/data/ from published
// dictionaries, and measures the engine's spelling rules against them.
//
//   node --import ./scripts/sound/ts-resolve.mjs scripts/sound/build.mjs --src <folder> [--only fr,de]
//
// <folder> holds the downloads named in docs/language/PHONETICS.md (it says where each comes
// from, its version and licence, and how to fetch it):
//   kaikki_<lang>.tsv        word<TAB>IPA[<TAB>IPA…], reduced from kaikki.org's Wiktionary extract
//                            by scripts/sound/kaikki-filter.py           (es it pt de ru id)
//   hin_deva_broad.tsv       WikiPron                                    (hi)
//   fra_latn_broad.tsv       WikiPron                                    (fr)
//   tha_thai_broad.tsv       WikiPron                                    (th)
//   unihan/Unihan_Readings.txt, cedict.txt                               (zh)
//   kaikki_pl.tsv, kor_hang_narrow.tsv, vie_latn_hanoi_narrow.tsv, JMdict_e   (test sets only)
//
// It writes one module per language and docs/language/measurements.json. The tables are data:
// the same sources give the same bytes. A light script: it reads a few megabytes per language.
